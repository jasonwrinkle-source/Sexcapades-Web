                if (!input) return;
                const val = seed(p);
                if (typeof sxWidenIntensitySlider === "function") { try { sxWidenIntensitySlider(input, val); } catch (err) {} }
                const lo = Number(input.min || -100), hi = Number(input.max || 100);
